"""Flask app for the Wardrobe Lookbook viewer (self-contained).

- GET /                  -> viewer page (templates/index.html)
- GET /api/combinations  -> all outfits as JSON
- GET /images/<file>     -> serves the outfit images

Data is read from viewer_data.json (generated by build_assets.py); no database needed.
Runs both as a dev server (python app.py) and inside the packaged desktop build (desktop.py).
"""
import json
import os
import sys
import tempfile

from flask import Flask, jsonify, render_template, request, send_from_directory


def resource_path(rel):
    """Absolute path to a bundled resource, both in dev and in a PyInstaller build."""
    base = getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(base, rel)


# 2:3-normalized web JPEGs (fall back to source PNGs if the web folder is absent).
IMAGE_DIR = resource_path("wardrobe_web")
if not os.path.isdir(IMAGE_DIR):
    IMAGE_DIR = resource_path("wardrobe_images")

DATA_JSON = resource_path("viewer_data.json")

# Writable per-user state: the wardrobe (owned garments) and wishlist (wanted garments). Each is a
# map of item key -> list of *holders* that keep the garment in the set: outfit ids (combo_id) plus
# a "manual" sentinel for garments added directly. A garment stays until its last holder is removed,
# so removing one of two outfits that share a garment leaves the garment (and the other outfit)
# intact. Item keys look like "shirt|White" or "shoe|Dark Brown|Derby". Lives under %APPDATA% so it
# survives app reinstalls and is editable outside the app; falls back next to the code in dev / on
# platforms without APPDATA. A legacy flat list ["shirt|White", ...] is still accepted on read.
DEFAULT_STATE = {"wardrobe": {}, "wishlist": {}, "patterns": {}, "custom": []}

# Fields kept on a user-created ("custom") outfit, same flat shape as a viewer_data.json outfit.
_CUSTOM_STR_KEYS = (
    "amb_hex", "img",
    "shirt_color", "shirt_hex", "shirt_pattern", "shirt_accent_color", "shirt_accent_hex",
    "trouser_color", "trouser_hex", "belt_color", "belt_hex",
    "shoe_color", "shoe_hex", "shoe_type",
    "dial_color", "dial_hex", "strap_color", "strap_hex",
)
_MAX_IMG = 6 * 1024 * 1024  # ~6 MB cap on an attached photo's data URL


def _clean_set(value):
    """Normalise a persisted set to { item_key: [holder, ...] }.

    Accepts the current dict shape (key -> list of holders) and the legacy flat list of keys
    (each becomes a single "manual" holder), so a hand-edited or pre-release file can't break.
    """
    out = {}
    if isinstance(value, dict):
        for k, holders in value.items():
            if not isinstance(k, str):
                continue
            if isinstance(holders, list):
                hs = [str(h) for h in holders if isinstance(h, (str, int))]
            else:
                hs = []
            out[k] = hs or ["manual"]
    elif isinstance(value, list):
        for k in value:
            if isinstance(k, (str, int)):
                out[str(k)] = ["manual"]
    return out


def _clean_patterns(value):
    """Normalise the pattern overrides to { "combo_id|slot": {pattern, accent, accentHex} }.

    Panel-set, per-user layer over the outfit data (the outfit source is never written). Drops
    anything malformed or "Solid" so a hand-edited file can't break the viewer.
    """
    out = {}
    if isinstance(value, dict):
        for k, v in value.items():
            if not isinstance(k, str) or not isinstance(v, dict):
                continue
            pat = v.get("pattern")
            if not isinstance(pat, str) or not pat or pat == "Solid":
                continue
            acc = v.get("accentHex")
            name = v.get("accent")
            out[k] = {
                "pattern": pat,
                "accent": name if isinstance(name, str) else "",
                "accentHex": acc if isinstance(acc, str) else "",
            }
    return out


def _clean_custom(value):
    """Normalise user-created outfits to a list of flat outfit dicts (same shape as viewer_data).

    Per-user layer in state.json; the built outfit data is never written. Keeps only known string
    fields, requires a combo_id, forces category "Custom" and custom=True, and drops an oversized
    attached image so a bad payload can't bloat the file.
    """
    out = []
    if not isinstance(value, list):
        return out
    for item in value:
        if not isinstance(item, dict):
            continue
        cid = item.get("combo_id")
        if not isinstance(cid, str) or not cid:
            continue
        rec = {"combo_id": cid, "category": "Custom", "custom": True}
        for k in _CUSTOM_STR_KEYS:
            v = item.get(k)
            if isinstance(v, str) and v:
                if k == "img" and len(v) > _MAX_IMG:
                    continue
                rec[k] = v
        out.append(rec)
    return out


def state_path():
    base = os.environ.get("APPDATA")
    if base:
        base = os.path.join(base, "Wardrobe Lookbook")
    else:
        base = os.path.dirname(os.path.abspath(__file__))
    os.makedirs(base, exist_ok=True)
    return os.path.join(base, "state.json")


def load_state():
    try:
        with open(state_path(), "r", encoding="utf-8") as f:
            data = json.load(f)
    except (FileNotFoundError, ValueError, OSError):
        return {"wardrobe": {}, "wishlist": {}, "patterns": {}, "custom": []}
    # Normalise to key -> holders, so a hand-edited or legacy file can't break the app.
    return {
        "wardrobe": _clean_set(data.get("wardrobe")),
        "wishlist": _clean_set(data.get("wishlist")),
        "patterns": _clean_patterns(data.get("patterns")),
        "custom": _clean_custom(data.get("custom")),
    }


def save_state(obj):
    """Atomically write state.json (temp file in the same dir, then replace)."""
    path = state_path()
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(obj, f, ensure_ascii=False)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.remove(tmp)
        raise

app = Flask(
    __name__,
    template_folder=resource_path("templates"),
    static_folder=resource_path("static"),
)


def load_outfits():
    """Return the flat outfit list from viewer_data.json (run build_assets.py to (re)generate)."""
    with open(DATA_JSON, "r", encoding="utf-8") as f:
        return json.load(f)


@app.route("/")
def index():
    return render_template("index.html", outfits=load_outfits())


@app.route("/api/combinations")
def api_combinations():
    return jsonify(load_outfits())


@app.route("/api/state", methods=["GET", "POST"])
def api_state():
    if request.method == "POST":
        body = request.get_json(silent=True) or {}
        clean = {
            "wardrobe": _clean_set(body.get("wardrobe")),
            "wishlist": _clean_set(body.get("wishlist")),
            "patterns": _clean_patterns(body.get("patterns")),
            "custom": _clean_custom(body.get("custom")),
        }
        save_state(clean)
        return jsonify(clean)
    return jsonify(load_state())


@app.route("/images/<path:fname>")
def images(fname):
    return send_from_directory(IMAGE_DIR, fname)


if __name__ == "__main__":
    app.run(host="127.0.0.1", port=5000, debug=True)
